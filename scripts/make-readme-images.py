#!/usr/bin/env python3
"""Generate every image the README uses, from the kit itself. Needs Chrome or Chromium for the PNGs.

  python3 scripts/make-readme-images.py

Writes:
  docs/img/hero-y2k.png        Rocha's example altar in the y2k-blog motif (1600x900)
  docs/img/triptych.png        the same altar in analog | cyberpunk | y2k-blog, each rendered at 2560x1600
  docs/img/arrange.png         arrange.html with a few things on the shelves
  docs/img/step-01..05.svg     pixel step badges for "Start here"
  docs/img/divider.svg         a gold pixel hairline
  docs/img/heart.svg           a pixel heart
  docs/IMAGES.md               the list of all of the above
The badge, divider and heart drawings are the same as the sibling kit desktop-core's.
"""
from __future__ import annotations

import datetime as dt
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
import build  # noqa: E402
import render  # noqa: E402

IMG = ROOT / "docs" / "img"
ORDER = ("analog", "cyberpunk", "y2k-blog")
NOW = dt.datetime(2026, 10, 28, 12, 0, tzinfo=dt.timezone.utc)
DIGITS = {"0": ["111", "101", "101", "101", "111"], "1": ["010", "110", "010", "010", "111"],
          "2": ["111", "001", "111", "100", "111"], "3": ["111", "001", "111", "001", "111"],
          "4": ["101", "101", "111", "001", "001"], "5": ["111", "100", "111", "001", "111"]}


def _pixels(text: str, x0: int, y0: int) -> str:
    return "".join(f"M{x0 + n * 4 + c} {y0 + r}h1v1h-1z" for n, ch in enumerate(text)
                   for r, row in enumerate(DIGITS[ch]) for c, bit in enumerate(row) if bit == "1")


def badge(num: str, ground: str, gold: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 11 9" width="33" height="27" '
            f'shape-rendering="crispEdges"><path fill="{ground}" d="M1 0h9v1h1v7h-1v1H1v-1H0V1h1z"/>'
            f'<path fill="{gold}" d="{_pixels(num, 2, 2)}"/></svg>\n')


def divider(gold: str) -> str:
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="720" height="6" shape-rendering="crispEdges">'
            '<defs><pattern id="p" width="12" height="6" patternUnits="userSpaceOnUse">'
            f'<rect width="6" height="2" y="2" fill="{gold}"/><rect x="8" y="2" width="2" height="2" fill="{gold}"/>'
            '</pattern></defs><rect width="720" height="6" fill="url(#p)"/></svg>\n')


def heart(colour: str) -> str:
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 7 6" width="21" height="18" shape-rendering="crispEdges">'
            f'<path fill="{colour}" d="M1 0h2v1h1V0h2v1h1v2H6v1H5v1H4v1H3V5H2V4H1V3H0V1h1z"/></svg>\n')


def strip_html(cells: list[tuple[str, str]], ground: str, gold: str, cream: str) -> str:
    figs = "".join(f'<figure><img src="{src}"><figcaption>{cap}</figcaption></figure>' for cap, src in cells)
    return f"""<!doctype html><html><head><meta charset="utf-8">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Silkscreen&display=swap">
<style>*{{margin:0;box-sizing:border-box}}body{{width:1620px;height:420px;background:{ground};display:flex;gap:24px;
padding:22px 30px;justify-content:center;align-items:flex-start}}figure{{display:flex;flex-direction:column;align-items:center;gap:10px}}
img{{width:500px;height:auto;border:2px solid {gold};display:block}}figcaption{{font-family:"Silkscreen",monospace;color:{cream};font-size:20px}}
</style></head><body>{figs}</body></html>"""


IMAGES_MD = """# Images

Every image here is generated by `scripts/make-readme-images.py` from the kit itself, using Rocha's example altar
(`examples/altar.rocha-coded.json`) and the drawn objects in `objects/`. No photos, no real people.

| File | What it is |
|---|---|
| `docs/img/hero-y2k.png` | Rocha's example altar in the y2k-blog motif at 1600x900, used as the README hero |
| `docs/img/triptych.png` | the same altar in analog, cyberpunk and y2k-blog, each rendered at 2560x1600 |
| `docs/img/arrange.png` | arrange.html with a few things placed on the top shelf |
| `docs/img/step-01.svg` to `step-05.svg` | pixel step badges for "Start here" |
| `docs/img/divider.svg` | a gold pixel hairline between README sections |
| `docs/img/heart.svg` | the pixel heart beside "If it goes wrong" and the guestbook line |

Painted cutouts in `objects/painted/` (when present) are generated art for Rocha's example altar, made for this kit.
They show objects only, never people. Each one is listed here when it is added.
"""


def main() -> int:
    style, _ = build.load_style(build.STYLE_EXAMPLE)
    pal = style["palette"]
    ground, gold, cream, candy = pal["hero"], pal["gold"], pal["paper"], pal["accent"]
    IMG.mkdir(parents=True, exist_ok=True)
    for i in range(1, 6):
        (IMG / f"step-{i:02d}.svg").write_text(badge(f"{i:02d}", ground, gold), encoding="utf-8")
    (IMG / "divider.svg").write_text(divider(gold), encoding="utf-8")
    (IMG / "heart.svg").write_text(heart(candy), encoding="utf-8")
    (ROOT / "docs" / "IMAGES.md").write_text(IMAGES_MD, encoding="utf-8")
    print("SVGs and docs/IMAGES.md written")
    if not render.find_chrome():
        print(render.NO_CHROME)
        return 1
    cfg = json.loads(build.HER_ALTAR.read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        res = build.build(cfg, tmp / "hero", "y2k-blog", build.STYLE_EXAMPLE, "1600x900", ROOT, True, NOW)
        if not res["png"]:
            print(res["message"])
            return 1
        (IMG / "hero-y2k.png").write_bytes(res["png"].read_bytes())
        cells = []
        for motif in ORDER:
            r = build.build(cfg, tmp / motif, motif, build.STYLE_EXAMPLE, "2560x1600", ROOT, True, NOW)
            cells.append((motif, r["png"].as_uri()))
        strip = tmp / "triptych.html"
        strip.write_text(strip_html(cells, ground, gold, cream), encoding="utf-8")
        ok, msg = render.screenshot(strip.as_uri(), IMG / "triptych.png", 1620, 420)
        print(msg)
    picks = [build.OBJECT_TYPES.index(t) for t in ("crescent-moon", "candle", "intention-card", "seashell", "rose")]
    out = render.run_arrange(ROOT / "arrange.html", picks, cfg["name"], cfg["intention"], cfg["daily_line"],
                             "y2k-blog", shot=IMG / "arrange.png")
    print("docs/img/arrange.png" if "error" not in out else out["error"])
    print("docs/img/hero-y2k.png (1600x900)")
    return 0 if ok and "error" not in out else 1


if __name__ == "__main__":
    sys.exit(main())
